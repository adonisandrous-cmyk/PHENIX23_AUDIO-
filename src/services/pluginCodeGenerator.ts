import { VisualizerSettings } from '../types/visualizer';
import { generateNativeColorLut, hexToRgb } from './paletteService';

export function generateAimpCppSource(settings: VisualizerSettings, paletteName: string): string {
  const lut = generateNativeColorLut(settings.customStops, 256);
  const lutFormatted = lut.map((val, idx) => `0x${val.toString(16).padStart(8, '0')}${idx % 8 === 7 ? ',\n    ' : ', '}`).join('');

  return `// ============================================================================
// AIMP Native Visual Plugin - C++ Windows Implementation
// Compatible with AIMP v4.x / v5.x Visual Plugin Architecture
// Generated by AIMP Audio Visualizer Studio
// Visualizer Mode: ${settings.mode.toUpperCase()}
// Palette: ${paletteName}
// ============================================================================

#include <windows.h>
#include <gdiplus.h>
#include <math.h>

#pragma comment(lib, "gdiplus.lib")
using namespace Gdiplus;

// --- AIMP SDK DEFINITIONS ---
#define AIMP_VISUAL_SPECTRUM_MAX 512
#define AIMP_VISUAL_WAVEFORM_MAX 512
#define AIMP_VISUAL_PLUGIN_FLAG_SPECTRUM 0x1
#define AIMP_VISUAL_PLUGIN_FLAG_WAVEFORM 0x2

#pragma pack(push, 1)
typedef struct _AIMPVisualData {
    int Width;
    int Height;
    float Spectrum[2][AIMP_VISUAL_SPECTRUM_MAX];
    float Waveform[2][AIMP_VISUAL_WAVEFORM_MAX];
    int Peak[2];
} AIMPVisualData, *PAIMPVisualData;
#pragma pack(pop)

// Forward declarations
class CAIMPVisualPlugin;

// Pre-computed 256-color LUT in COLORREF format (0x00BBGGRR)
static const DWORD COLOR_PALETTE_LUT[256] = {
    ${lutFormatted}
};

// Physics and smoothing constants
static const float SMOOTHING_FACTOR = ${settings.smoothing.toFixed(3)}f;
static const float PEAK_GRAVITY = ${settings.peakGravity.toFixed(2)}f * 980.0f;
static const DWORD PEAK_HOLD_MS = ${settings.peakHoldMs}UL;
static const float PREAMP_GAIN = ${settings.sensitivity.toFixed(2)}f;

// Floating peak cap state
struct PeakBar {
    float Height;
    float PeakValue;
    DWORD LastPeakTime;
    float Velocity;
};

static PeakBar g_Bars[64];
static ULONG_PTR g_GdiplusToken = 0;

// Initialize GDI+ and plugin state
BOOL WINAPI DllMain(HINSTANCE hinstDLL, DWORD fdwReason, LPVOID lpvReserved) {
    switch (fdwReason) {
        case DLL_PROCESS_ATTACH: {
            GdiplusStartupInput gdiplusStartupInput;
            GdiplusStartup(&g_GdiplusToken, &gdiplusStartupInput, NULL);
            ZeroMemory(g_Bars, sizeof(g_Bars));
            break;
        }
        case DLL_PROCESS_DETACH: {
            GdiplusShutdown(g_GdiplusToken);
            break;
        }
    }
    return TRUE;
}

// ----------------------------------------------------------------------------
// Visual Rendering Function called by AIMP engine on every frame
// ----------------------------------------------------------------------------
extern "C" __declspec(dllexport) void WINAPI AIMPVisual_Render(HDC hdc, PAIMPVisualData pData) {
    if (!hdc || !pData || pData->Width <= 0 || pData->Height <= 0) return;

    int width = pData->Width;
    int height = pData->Height;
    DWORD now = GetTickCount();

    // Create double-buffer bitmap for tear-free 60+ FPS rendering
    HDC memDC = CreateCompatibleDC(hdc);
    HBITMAP memBM = CreateCompatibleBitmap(hdc, width, height);
    HBITMAP oldBM = (HBITMAP)SelectObject(memDC, memBM);

    // Dark background clear
    HBRUSH bgBrush = CreateSolidBrush(RGB(10, 10, 12));
    RECT rc = { 0, 0, width, height };
    FillRect(memDC, &rc, bgBrush);
    DeleteObject(bgBrush);

    const int numBars = 64;
    const int barGap = ${settings.barGap};
    float barWidth = max(2.0f, (float)(width - (numBars - 1) * barGap) / (float)numBars);
    float usableH = (float)height * ${settings.showFloorReflection ? '0.65f' : '0.88f'};
    float baseY = usableH;

    for (int i = 0; i < numBars; i++) {
        // Logarithmic frequency scale mapping
        float logPos = powf((float)i / (float)numBars, 1.6f);
        int freqIdx = (int)(logPos * (AIMP_VISUAL_SPECTRUM_MAX * 0.75f));
        if (freqIdx >= AIMP_VISUAL_SPECTRUM_MAX) freqIdx = AIMP_VISUAL_SPECTRUM_MAX - 1;

        // Stereo split or combined
        float leftVal = pData->Spectrum[0][freqIdx];
        float rightVal = pData->Spectrum[1][freqIdx];
        float rawVal = (leftVal + rightVal) * 0.5f * PREAMP_GAIN;
        if (rawVal > 1.0f) rawVal = 1.0f;

        float targetH = rawVal * usableH;
        g_Bars[i].Height = g_Bars[i].Height + (targetH - g_Bars[i].Height) * (1.0f - SMOOTHING_FACTOR);

        float h = g_Bars[i].Height;
        float x = i * (barWidth + barGap);

        // Peak Hold & Falloff
        if (h >= g_Bars[i].PeakValue) {
            g_Bars[i].PeakValue = h;
            g_Bars[i].LastPeakTime = now;
            g_Bars[i].Velocity = 0.0f;
        } else {
            if (now - g_Bars[i].LastPeakTime > PEAK_HOLD_MS) {
                g_Bars[i].Velocity += PEAK_GRAVITY * 0.016f; // delta time ~16ms
                g_Bars[i].PeakValue = max(0.0f, g_Bars[i].PeakValue - g_Bars[i].Velocity * 0.016f);
            }
        }

        if (h > 1.0f) {
            int lutIdx = min(255, (int)((h / usableH) * 255.0f));
            DWORD barColor = COLOR_PALETTE_LUT[lutIdx];

            HBRUSH barBrush = CreateSolidBrush(barColor);
            RECT barRc = { (LONG)x, (LONG)(baseY - h), (LONG)(x + barWidth), (LONG)baseY };
            FillRect(memDC, &barRc, barBrush);
            DeleteObject(barBrush);

            ${settings.showFloorReflection ? `
            // Floor Reflection
            HBRUSH reflBrush = CreateSolidBrush(RGB(GetRValue(barColor)/4, GetGValue(barColor)/4, GetBValue(barColor)/4));
            RECT reflRc = { (LONG)x, (LONG)(baseY + 2), (LONG)(x + barWidth), (LONG)(baseY + 2 + h * 0.35f) };
            FillRect(memDC, &reflRc, reflBrush);
            DeleteObject(reflBrush);
            ` : ''}
        }

        ${settings.showPeaks ? `
        // Draw Peak Cap
        if (g_Bars[i].PeakValue > 2.0f) {
            int peakIdx = min(255, (int)((g_Bars[i].PeakValue / usableH) * 255.0f));
            DWORD peakColor = COLOR_PALETTE_LUT[peakIdx];
            HBRUSH capBrush = CreateSolidBrush(peakColor);
            RECT capRc = { (LONG)x, (LONG)(baseY - g_Bars[i].PeakValue - 3), (LONG)(x + barWidth), (LONG)(baseY - g_Bars[i].PeakValue) };
            FillRect(memDC, &capRc, capBrush);
            DeleteObject(capBrush);
        }
        ` : ''}
    }

    // BitBlt final buffer to window DC
    BitBlt(hdc, 0, 0, width, height, memDC, 0, 0, SRCCOPY);

    SelectObject(memDC, oldBM);
    DeleteObject(memBM);
    DeleteDC(memDC);
}

// ----------------------------------------------------------------------------
// AIMP Plugin Header Export
// ----------------------------------------------------------------------------
extern "C" __declspec(dllexport) DWORD WINAPI AIMPPlugin_GetFlags() {
    return AIMP_VISUAL_PLUGIN_FLAG_SPECTRUM | AIMP_VISUAL_PLUGIN_FLAG_WAVEFORM;
}

extern "C" __declspec(dllexport) const WCHAR* WINAPI AIMPPlugin_GetName() {
    return L"AIMP Visualizer Studio - ${paletteName}";
}

extern "C" __declspec(dllexport) const WCHAR* WINAPI AIMPPlugin_GetAuthor() {
    return L"AIMP Visualizer Studio";
}
`;
}

export function generateWinampVisSource(settings: VisualizerSettings, paletteName: string): string {
  const lut = generateNativeColorLut(settings.customStops, 256);
  const lutFormatted = lut.map((val, idx) => `0x${val.toString(16).padStart(8, '0')}${idx % 8 === 7 ? ',\n    ' : ', '}`).join('');

  return `// ============================================================================
// Winamp Visualizer Plugin (.DLL) - Natively supported by AIMP Player!
// AIMP includes a Winamp wrapper module (aimp_vis_winamp) that runs this directly.
// Palette: ${paletteName}
// ============================================================================

#include <windows.h>
#include <math.h>

// Standard Winamp Visualization API definitions
typedef struct winampVisModule {
    char *description;
    HWND hwndParent;
    HINSTANCE hDllInstance;
    int sRate;
    int nCh;
    int latencyMs;
    int delayMs;
    int spectrumNch;
    int waveformNch;
    unsigned char spectrumData[2][576];
    unsigned char waveformData[2][576];
    void (*Config)(struct winampVisModule *this_mod);
    int (*Init)(struct winampVisModule *this_mod);
    int (*Render)(struct winampVisModule *this_mod);
    void (*Quit)(struct winampVisModule *this_mod);
    void *userData;
} winampVisModule;

typedef struct {
    int version;
    char *description;
    winampVisModule* (*getModule)(int which);
} winampVisHeader;

static const DWORD PALETTE_LUT[256] = {
    ${lutFormatted}
};

static HWND g_hVisWnd = NULL;
static float g_smoothedBars[64] = { 0 };

int visInit(winampVisModule *this_mod) {
    // Window creation or rendering viewport initialization
    return 0;
}

int visRender(winampVisModule *this_mod) {
    if (!this_mod->hwndParent) return 0;

    RECT rc;
    GetClientRect(this_mod->hwndParent, &rc);
    int width = rc.right - rc.left;
    int height = rc.bottom - rc.top;
    if (width <= 0 || height <= 0) return 0;

    HDC hdc = GetDC(this_mod->hwndParent);
    HDC memDC = CreateCompatibleDC(hdc);
    HBITMAP memBM = CreateCompatibleBitmap(hdc, width, height);
    HBITMAP oldBM = (HBITMAP)SelectObject(memDC, memBM);

    // Background fill
    HBRUSH bg = CreateSolidBrush(RGB(10, 10, 12));
    FillRect(memDC, &rc, bg);
    DeleteObject(bg);

    const int numBars = 64;
    float barW = (float)width / (float)numBars;

    for (int i = 0; i < numBars; i++) {
        int sampleIdx = min(575, (int)(powf((float)i / (float)numBars, 1.5f) * 400.0f));
        float rawVal = (float)this_mod->spectrumData[0][sampleIdx] / 255.0f;

        g_smoothedBars[i] += (rawVal - g_smoothedBars[i]) * (1.0f - ${settings.smoothing.toFixed(3)}f);
        float h = g_smoothedBars[i] * (float)height * 0.85f;

        int lutIdx = min(255, (int)((g_smoothedBars[i]) * 255.0f));
        HBRUSH bBrush = CreateSolidBrush(PALETTE_LUT[lutIdx]);
        RECT bRc = { (LONG)(i * barW), (LONG)(height - h), (LONG)((i + 1) * barW - 1), (LONG)height };
        FillRect(memDC, &bRc, bBrush);
        DeleteObject(bBrush);
    }

    BitBlt(hdc, 0, 0, width, height, memDC, 0, 0, SRCCOPY);
    SelectObject(memDC, oldBM);
    DeleteObject(memBM);
    DeleteDC(memDC);
    ReleaseDC(this_mod->hwndParent, hdc);

    return 0;
}

void visQuit(winampVisModule *this_mod) {
    // Cleanup
}

static winampVisModule g_mod = {
    "AIMP Visualizer - ${paletteName}",
    NULL,
    NULL,
    0, 0, 0, 0,
    2, 2,
    {0}, {0},
    NULL,
    visInit,
    visRender,
    visQuit,
    NULL
};

winampVisModule* getModule(int which) {
    if (which == 0) return &g_mod;
    return NULL;
}

static winampVisHeader g_hdr = {
    0x020, // VIS_HDRVER
    "AIMP Visualizer Studio Plugin",
    getModule
};

extern "C" __declspec(dllexport) winampVisHeader* winampVisGetHeader() {
    return &g_hdr;
}
`;
}

