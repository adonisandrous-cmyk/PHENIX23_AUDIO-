export function generateAimpIniConfig(settings: VisualizerSettings, paletteName: string): string {
  const stopsIni = settings.customStops.map((s, idx) => {
    const { r, g, b } = hexToRgb(s.color);
    return `Stop${idx}_Pos=${s.position.toFixed(3)}\nStop${idx}_RGB=${r},${g},${b}`;
  }).join('\n');

  return `[AIMP_VISUALIZER_STUDIO]
Version=1.0
Mode=${settings.mode}
PaletteName=${paletteName}
Smoothing=${settings.smoothing.toFixed(3)}
Sensitivity=${settings.sensitivity.toFixed(2)}
PeakHoldMs=${settings.peakHoldMs}
PeakGravity=${settings.peakGravity.toFixed(2)}
GlowIntensity=${settings.glowIntensity.toFixed(2)}
DecayRate=${settings.decayRate.toFixed(3)}
ShowPeaks=${settings.showPeaks ? 1 : 0}
ShowFloorReflection=${settings.showFloorReflection ? 1 : 0}
StereoMode=${settings.stereoMode}
BarGap=${settings.barGap}

[COLOR_STOPS]
Count=${settings.customStops.length}
${stopsIni}
`;
}

